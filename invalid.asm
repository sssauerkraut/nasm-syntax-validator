; Неправильные комбинации
mov 5, eax        ; константа не может быть первым операндом
add 10, ebx       ; константа не может быть первым операндом
add [eax], [ebx]  ; два операнда памяти (недопустимо)
sub 5, 10         ; две константы

; Неправильные размеры (если добавите проверку)
add al, 1000      ; imm16 в 8-битную инструкцию (warning)

; Недостаточно операндов
mov eax
add

; Лишние символы
mov eax, 10, 20